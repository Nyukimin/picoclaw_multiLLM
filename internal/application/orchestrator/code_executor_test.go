// ヘルパー関数
func noopEventEmitter(eventType, from, to, content, route, jobID, sessionID, channel, chatID string) {
	// テスト用の空実装
}

type failingCoderAgent struct {
	err error
}

func (m *failingCoderAgent) Generate(ctx context.Context, t task.Task, systemPrompt string) (string, error) {
	return "", m.err
}

type codeExecutorEvent struct {
	eventType string
	from      string
	to        string
	content   string
	route     string
	jobID     string
	sessionID string
	channel   string
	chatID    string
}

func recordingCodeEventEmitter(events *[]codeExecutorEvent) func(eventType, from, to, content, route, jobID, sessionID, channel, chatID string) {
	return func(eventType, from, to, content, route, jobID, sessionID, channel, chatID string) {
		*events = append(*events, codeExecutorEvent{
			eventType: eventType,
			from:      from,
			to:        to,
			content:   content,
			route:     route,
			jobID:     jobID,
			sessionID: sessionID,
			channel:   channel,
			chatID:    chatID,
		})
	}
}

func findCodeExecutorEvent(events []codeExecutorEvent, eventType, from, to string) (codeExecutorEvent, bool) {
	for _, event := range events {
		if event.eventType == eventType && event.from == from && event.to == to {
			return event, true
		}
	}
	return codeExecutorEvent{}, false
}

type recordingCodeWorkerExecutionService struct {
	calls    int
	jobID    task.JobID
	proposal *proposal.Proposal
	err      error
}

func (s *recordingCodeWorkerExecutionService) ExecuteProposal(ctx context.Context, jobID task.JobID, p *proposal.Proposal) (*patch.PatchExecutionResult, error) {
	s.calls++
	s.jobID = jobID
	s.proposal = p
	if s.err != nil {
		return nil, s.err
	}
	result := patch.NewPatchExecutionResult()
	result.AddResult(patch.CommandResult{Success: true, Output: "ok"})
	return result.WithSummary("実行: 1 件, 成功: 1 件, 失敗: 0 件"), nil
}

type recordingCoderProposalEvidenceRecorder struct {
	items []domainskill.CoderProposalEvidence
	err   error
}

func (r *recordingCoderProposalEvidenceRecorder) SaveCoderProposalEvidence(_ context.Context, item domainskill.CoderProposalEvidence) (domainskill.CoderProposalEvidencePaths, error) {
	r.items = append(r.items, item)
	if r.err != nil {
		return domainskill.CoderProposalEvidencePaths{}, r.err
	}
	return domainskill.CoderProposalEvidencePaths{
		RootPath:            "workspace/logs/skill_governance/coder_evidence/job",
		SkillDiffPath:       "workspace/logs/skill_governance/coder_evidence/job/skill_diff.md",
		AgentTranscriptPath: "workspace/logs/skill_governance/coder_evidence/job/agent_transcript.md",
	}, nil
}
