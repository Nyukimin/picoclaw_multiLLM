// TestCodeExecutor_CODE3_WithProposal はCODE3 Proposal実行のテスト（RED）
func TestCodeExecutor_CODE3_WithProposal(t *testing.T) {
	testProposal := proposal.NewProposal(
		"Test plan",
		`[{"type": "file_edit", "action": "create", "target": "test.txt", "content": "test"}]`,
		"Low risk",
		"Low cost",
	)

	coder3 := &mockCoderAgentWithProposal{
		response: "Proposal generated",
		proposal: testProposal,
	}

	workerService := &recordingCodeWorkerExecutionService{}
	executor := NewDefaultCodeExecutor(nil, nil, coder3, nil, workerService, nil, noopEventEmitter)

	jobID := task.NewJobID()
	req := CodeExecutionRequest{
		Task:      task.NewTask(jobID, "user message", "test", "chat-1"),
		Route:     routing.RouteCODE3,
		SessionID: "sess-1",
		Channel:   "test",
		ChatID:    "chat-1",
		JobID:     jobID.String(),
	}

	resp, err := executor.ExecuteCode(context.Background(), req)
	if err != nil {
		t.Fatalf("Expected no error, got %v", err)
	}

	if !resp.Handled {
		t.Error("CODE3 with Proposal should be handled via Proposal path")
	}

	// レスポンスにPlanが含まれることを確認
	if resp.Response == "" {
		t.Error("Expected non-empty response")
	}
	if workerService.calls != 1 {
		t.Fatalf("worker ExecuteProposal calls=%d, want 1", workerService.calls)
	}
	if workerService.jobID.String() != jobID.String() {
		t.Fatalf("worker jobID=%s, want %s", workerService.jobID.String(), jobID.String())
	}
	if workerService.proposal != testProposal {
		t.Fatal("worker should receive the same proposal instance generated by coder")
	}
}

